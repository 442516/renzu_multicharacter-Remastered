local FALLBACK_LOCALE = 'en'

function Locale(key, lang)
	lang = lang or (Config and Config.Locale) or FALLBACK_LOCALE
	local table_ = Locales[lang] or Locales[FALLBACK_LOCALE] or {}
	return table_[key] or (Locales[FALLBACK_LOCALE] and Locales[FALLBACK_LOCALE][key]) or key
end

function GetActiveLocaleTable(lang)
	lang = lang or (Config and Config.Locale) or FALLBACK_LOCALE
	return Locales[lang] or Locales[FALLBACK_LOCALE] or {}
end